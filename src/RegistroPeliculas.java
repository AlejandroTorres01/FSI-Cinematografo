    private void BRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistroActionPerformed
        String cla = TFClave.getText();
        String tit = TFTitulo.getText();
        ImageIcon car = new ImageIcon(cnx.escalarImagen(cartel.getImage(), 300, 400));

        Peliculas pp = new Peliculas(cla, tit, car);
        if (pp.insertar(cnx) == 1) {
            cnx.entablar("SELECT * FROM peliculas", TablaPeliculas, 20, 40, 40);
            
            TFClave.setText("");
            TFTitulo.setText("");
            cartel = null;
            JCartel.setIcon(null);
            
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar la película");
        }
    }//GEN-LAST:event_BRegistroActionPerformed

    private void BCartelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BCartelActionPerformed
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = fc.getSelectedFile();
            cartel = new ImageIcon(archivo.getPath());
            JCartel.setIcon(new ImageIcon(cnx.escalarImagen(cartel.getImage(), 194, 235)));
        }
    }//GEN-LAST:event_BCartelActionPerformed

    private void TablaPeliculasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TablaPeliculasMousePressed
        int ren = TablaPeliculas.getSelectedRow();
        DefaultTableModel modelo = (DefaultTableModel) TablaPeliculas.getModel();
        if (ren >= 0) {
            TFClave.setText(modelo.getValueAt(ren, 0).toString());
            TFTitulo.setText(modelo.getValueAt(ren, 1).toString());
            cartel = new ImageIcon(cnx.escalarImagen(((ImageIcon) modelo.getValueAt(ren, 2)).
                    getImage(), 194, 235));
            JCartel.setIcon(cartel);
        }   

    }//GEN-LAST:event_TablaPeliculasMousePressed

